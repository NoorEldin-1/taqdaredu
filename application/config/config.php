if ( ! function_exists('tq_auth_gc'))
{
	function tq_auth_gc()
	{
		if (mt_rand(1, 50) !== 1)
		{
			return;
		}
		$db = tq_auth_db();
		if ($db === NULL)
		{
			return;
		}
		$db->where('attempted_at <', time() - 86400)->delete('tq_auth_login_attempts');
		$db->where('expires_at <', time() - 86400)->delete('tq_auth_password_resets');
	}
}

if ( ! function_exists('tq_auth_record_failure'))
{
	function tq_auth_record_failure($identifier, $scope = 'login')
	{
		$db = tq_auth_db();
		if ($db === NULL)
		{
			return;
		}
		$db->insert('tq_auth_login_attempts', array(
			'identifier'   => substr(strtolower(trim((string) $identifier)), 0, 191),
			'ip'           => substr(tq_auth_ip(), 0, 45),
			'scope'        => substr($scope, 0, 32),
			'attempted_at' => time(),
		));
		tq_auth_gc();
	}
}

if ( ! function_exists('tq_auth_clear_failures'))
{
	function tq_auth_clear_failures($identifier, $scope = 'login')
	{
		$db = tq_auth_db();
		if ($db === NULL)
		{
			return;
		}
		$db->where('scope', $scope)
		   ->where('identifier', substr(strtolower(trim((string) $identifier)), 0, 191))
		   ->where('ip', substr(tq_auth_ip(), 0, 45))
		   ->delete('tq_auth_login_attempts');
	}
}

