		$db = tq_auth_db();
		if ($db === NULL)
		{
			return 0;
		}
		$db->where('scope', $scope)->where('attempted_at >=', time() - TQ_AUTH_WINDOW);
		if ($by_ip_only)
		{
			$db->where('ip', substr(tq_auth_ip(), 0, 45));
		}
		else
		{
			$db->where('identifier', substr(strtolower(trim((string) $identifier)), 0, 191));
			$db->where('ip', substr(tq_auth_ip(), 0, 45));
		}
		return (int) $db->count_all_results('tq_auth_login_attempts');
	}
}

if ( ! function_exists('tq_auth_is_throttled'))
{
	/**
	 * TRUE when this (identifier, ip) pair burned TQ_AUTH_MAX_PER_USER tries,
	 * or when this IP alone burned TQ_AUTH_MAX_PER_IP tries, inside the window.
	 */
	function tq_auth_is_throttled($identifier, $scope = 'login')
	{
		if (tq_auth_failure_count($identifier, $scope) >= TQ_AUTH_MAX_PER_USER)
		{
			return TRUE;
		}
		return (tq_auth_failure_count(NULL, $scope, TRUE) >= TQ_AUTH_MAX_PER_IP);
	}
}

if ( ! function_exists('tq_auth_throttle_message'))
{
	function tq_auth_throttle_message()
	{
		$minutes = (int) ceil(TQ_AUTH_WINDOW / 60);
		return 'Too many failed attempts. Please try again in ' . $minutes . ' minutes.'
			. ' / تم تجاوز عدد المحاولات المسموح به، برجاء المحاولة بعد ' . $minutes . ' دقيقة.';
	}
}

/* ----------------------------------------------------------------------
 * 3) Password reset tokens  (table: tq_auth_password_resets)
 *    32 random bytes -> 64 hex chars, stored hashed, single use, 15 min TTL.
 * -------------------------------------------------------------------- */

if ( ! defined('TQ_AUTH_RESET_TTL')) define('TQ_AUTH_RESET_TTL', 900); // 15 minutes

if ( ! function_exists('tq_auth_reset_fingerprint'))
{
	function tq_auth_reset_fingerprint($token)
	{
		return hash('sha256', (string) $token);
	}
}

if ( ! function_exists('tq_auth_create_reset_token'))
{
	/**
	 * Issues a fresh single use reset token for $email and voids the previous
	 * unused ones. Returns the raw token (to be emailed) or FALSE.
	 */
	function tq_auth_create_reset_token($email)
	{
		$db = tq_auth_db();
		if ($db === NULL OR empty($email))
		{
			return FALSE;
		}
		$user = $db->get_where('users', array('email' => $email))->row_array();
		if (empty($user))
		{
			return FALSE;
		}
		// void any pending token for this account
		$db->where('email', $email)->where('used_at IS NULL', NULL, FALSE)
		   ->update('tq_auth_password_resets', array('used_at' => time()));

		$token = bin2hex(random_bytes(32));
		$now   = time();
		$db->insert('tq_auth_password_resets', array(
			'user_id'    => $user['id'],
			'email'      => $email,
			'token_hash' => tq_auth_reset_fingerprint($token),
			'created_at' => $now,
			'expires_at' => $now + TQ_AUTH_RESET_TTL,
			'used_at'    => NULL,
			'ip'         => substr(tq_auth_ip(), 0, 45),
		));
		return $token;
	}
}

if ( ! function_exists('tq_auth_find_reset_token'))
{
	/** Returns the reset row when the token is valid, unused and unexpired. */
	function tq_auth_find_reset_token($token)
	{
		$db = tq_auth_db();
		if ($db === NULL OR ! is_string($token) OR strlen($token) !== 64 OR ! ctype_xdigit($token))
		{
			return FALSE;
		}
		$row = $db->get_where('tq_auth_password_resets', array(
			'token_hash' => tq_auth_reset_fingerprint($token),
		))->row_array();

		if (empty($row) OR $row['used_at'] !== NULL OR (int) $row['expires_at'] < time())
		{
			return FALSE;
		}
		return $row;
	}
}

if ( ! function_exists('tq_auth_consume_reset_token'))
{
	/**
	 * Atomically burns the token (UPDATE ... WHERE used_at IS NULL) so a
	 * replayed link cannot change the password a second time.
	 * Returns the reset row on success, FALSE otherwise.
	 */
	function tq_auth_consume_reset_token($token)
	{
		$row = tq_auth_find_reset_token($token);
		if ($row === FALSE)
		{
			return FALSE;
		}
		$db = tq_auth_db();
		$db->where('id', $row['id'])
		   ->where('used_at IS NULL', NULL, FALSE)
		   ->update('tq_auth_password_resets', array('used_at' => time()));

		return ($db->affected_rows() === 1) ? $row : FALSE;
	}
}

/* ----------------------------------------------------------------------
 * 4) Same site check for authentication POSTs (CSRF mitigation that does
 *    not need a hidden token in the HTML). See the CSRF note above.
 * -------------------------------------------------------------------- */

if ( ! function_exists('tq_auth_verify_origin'))
{
	/**
	 * TRUE when the request is not a POST, when no Origin/Referer was sent
	 * (non browser client), or when the sent origin host equals the host the
	 * request was addressed to. FALSE only on a genuine cross-site POST.
	 */
	function tq_auth_verify_origin()
	{
		if ( ! isset($_SERVER['REQUEST_METHOD']) OR strtoupper($_SERVER['REQUEST_METHOD']) !== 'POST')
		{
			return TRUE;
		}
		$target = isset($_SERVER['HTTP_HOST']) ? strtolower($_SERVER['HTTP_HOST']) : '';
		if ($target === '')
		{
			return TRUE;
		}
		$source = '';
		if ( ! empty($_SERVER['HTTP_ORIGIN']))
		{
			$source = $_SERVER['HTTP_ORIGIN'];
		}
		elseif ( ! empty($_SERVER['HTTP_REFERER']))
		{
			$source = $_SERVER['HTTP_REFERER'];
		}
		if ($source === '' OR $source === 'null')
		{
			return TRUE; // curl / mobile app / privacy proxy: nothing to compare
		}
		$host = parse_url($source, PHP_URL_HOST);
		if (empty($host))
		{
			return TRUE;
		}
		$port = parse_url($source, PHP_URL_PORT);
		$host = strtolower($host) . ($port ? ':' . $port : '');

		return ($host === $target OR $host === preg_replace('/:\d+$/', '', $target));
	}
}
