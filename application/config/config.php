if ( ! function_exists('tq_auth_db'))
{
	/**
	 * Returns the shared CI database object, loading it when needed.
	 * Returns NULL when called outside of a CI request (e.g. CLI bootstrap).
	 */
	function tq_auth_db()
	{
		if ( ! function_exists('get_instance'))
		{
			return NULL;
		}
		$CI =& get_instance();
		if ( ! is_object($CI))
		{
			return NULL;
		}
		if ( ! isset($CI->db) OR ! is_object($CI->db))
		{
			@$CI->load->database();
		}
		return (isset($CI->db) && is_object($CI->db)) ? $CI->db : NULL;
	}
}

if ( ! function_exists('tq_auth_ip'))
{
	function tq_auth_ip()
	{
		if (function_exists('get_instance'))
		{
			$CI =& get_instance();
			if (is_object($CI) && isset($CI->input))
			{
				$ip = $CI->input->ip_address();
				if ( ! empty($ip))
				{
					return $ip;
				}
			}
		}
		return isset($_SERVER['REMOTE_ADDR']) ? $_SERVER['REMOTE_ADDR'] : '0.0.0.0';
	}
}

/* ----------------------------------------------------------------------
 * 1) Password hashing : password_hash() with transparent sha1 migration
 * -------------------------------------------------------------------- */

if ( ! function_exists('tq_password_is_legacy'))
{
	/** TRUE for the old unsalted sha1() digests (40 hex chars). */
	function tq_password_is_legacy($stored)
	{
		return (is_string($stored) && strlen($stored) === 40 && ctype_xdigit($stored));
	}
}

if ( ! function_exists('tq_password_hash'))
{
	function tq_password_hash($plain)
	{
		return password_hash((string) $plain, PASSWORD_DEFAULT);
	}
}

if ( ! function_exists('tq_password_matches'))
{
	/**
	 * Constant time check of a plain password against whatever is stored:
	 * a modern password_hash() digest, a legacy sha1() digest, or (defensively)
	 * a plain text value left over from an old import.
	 */
	function tq_password_matches($plain, $stored)
	{
		if ( ! is_string($stored) OR $stored === '' OR $plain === NULL OR $plain === '')
		{
			return FALSE;
		}
		if (tq_password_is_legacy($stored))
		{
			return hash_equals($stored, sha1((string) $plain));
		}
		if ($stored[0] === '$')
		{
			return password_verify((string) $plain, $stored);
		}
		return hash_equals($stored, (string) $plain);
	}
}

if ( ! function_exists('tq_password_needs_upgrade'))
{
	function tq_password_needs_upgrade($stored)
	{
		if ( ! is_string($stored) OR $stored === '')
		{
			return TRUE;
		}
		if ($stored[0] !== '$')
		{
			return TRUE; // sha1 or plain text
		}
		return password_needs_rehash($stored, PASSWORD_DEFAULT);
	}
}

if ( ! function_exists('tq_password_upgrade'))
{
	/**
	 * Progressive migration: called right after a SUCCESSFUL verification.
	 * Re-hashes the password with password_hash() and stores it. Never called
	 * on a failed login, so no existing account can be invalidated.
	 */
	function tq_password_upgrade($user_id, $plain, $stored)
	{
		if (empty($user_id) OR $plain === NULL OR $plain === '' OR ! tq_password_needs_upgrade($stored))
		{
			return FALSE;
		}
		$db = tq_auth_db();
		if ($db === NULL)
		{
			return FALSE;
		}
		$db->where('id', $user_id);
		$db->update('users', array('password' => tq_password_hash($plain)));
		return TRUE;
	}
}

if ( ! function_exists('tq_password_authenticate'))
{
	/**
	 * Verify + auto-upgrade in one call.
	 * $user is an array or object row coming from the users table.
	 */
	function tq_password_authenticate($user, $plain)
	{
		if (empty($user))
		{
			return FALSE;
		}
		$user = (array) $user;
		if ( ! isset($user['password']))
		{
			return FALSE;
		}
		if ( ! tq_password_matches($plain, $user['password']))
		{
			return FALSE;
		}
		if (isset($user['id']))
		{
			tq_password_upgrade($user['id'], $plain, $user['password']);
		}
		return TRUE;
	}
}

